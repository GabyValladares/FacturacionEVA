    public void actualizarDetalleFactura() {

        txtADetalle.setText("");

        iniciarFactura();

        for (DetalleFactura d : lDF) {

            txtADetalle.append(
                    String.format(
                            "%-22s %-8d %-10.2f %-10.2f\n",
                            d.getProducto().getNombre(),
                            d.getCantidad(),
                            d.getProducto().getPrecio(),
                            d.getSubtotal()
                    )
            );

        }

        txtADetalle.append(
                "----------------------------------------------------\n"
        );

        double subtotal = 0;

        // Calcular subtotal de todos los productos agregados
        for (DetalleFactura dF : lDF) {
            subtotal += dF.getSubtotal();
        }

        // =========================
        // CALCULAR DESCUENTO
        // =========================
        double descuento = 0;

        int indiceCliente = cmbClientes.getSelectedIndex();

        if (indiceCliente >= 0) {

            String tipo = lC.get(indiceCliente)[6];

            // Cliente regular y subtotal mayor a 1000
            if (tipo.equalsIgnoreCase("REGULAR") && subtotal > 1000) {
                descuento = subtotal * 0.05;
            }
        }

        // =========================
        // CALCULAR IVA
        // =========================
        double iva = 0;

        if (chkIVA.isSelected()) {
            iva = (subtotal - descuento) * 0.15;
        }

        // =========================
        // CALCULAR TOTAL
        // =========================
        double total = subtotal - descuento + iva;

        // =========================
        // MOSTRAR EN TEXTFIELDS
        // =========================
        txtSubTotal.setText(String.format("%.2f", subtotal));

        txtDescuento.setText(String.format("%.2f", descuento));

        txtIVA.setText(String.format("%.2f", iva));

        txtTotalPagar.setText(String.format("%.2f", total));

        // =========================
        // ACTUALIZAR TXTDETALLE
        // =========================
        txtADetalle.append(
                String.format("%35s %.2f\n", "SUBTOTAL:", subtotal)
        );

        txtADetalle.append(
                String.format("%35s %.2f\n", "DESCUENTO:", descuento)
        );

        txtADetalle.append(
                String.format("%35s %.2f\n", "IVA (15%):", iva)
        );

        txtADetalle.append(
                String.format("%35s %.2f\n", "TOTAL A PAGAR:", total)
        );

        txtADetalle.append(
                "----------------------------------------------------\n"
        );

        txtADetalle.append(
                "              Gracias por su compra\n"
        );

        txtADetalle.append(
                "----------------------------------------------------\n"
        );

    }

    public void actualizarTabla() {

        javax.swing.table.DefaultTableModel modelo
                = (javax.swing.table.DefaultTableModel) tblDetalle.getModel();

        modelo.setRowCount(0);

        for (DetalleFactura d : lDF) {

            modelo.addRow(new Object[]{
                d.getProducto().getNombre(),
                d.getCantidad(),
                d.getProducto().getPrecio(),
                d.getSubtotal()
            });
        }
    }

    public void calcularSubtotalSpinner() {

        if (cmbProductos.getSelectedIndex() >= 0
                && !txtPrecio.getText().isEmpty()) {

            double precio = Double.parseDouble(txtPrecio.getText());

            int cantidad = (int) spCantidad.getValue();

            double subtotal = precio * cantidad;

            txtSubTotal.setText(String.format("%.2f", subtotal));
        }
    }

    public double calcularTotal() {

        double total = 0;

        for (DetalleFactura d : lDF) {
            total += d.getSubtotal();
        }

        if (chkIVA.isSelected()) {
            total = total + (total * 0.15);
        }

        return total;
    }

    private void guardarFactura() {
        try {

            // Validar que exista un cliente seleccionado
            if (cmbClientes.getSelectedIndex() == -1) {

                JOptionPane.showMessageDialog(this,
                        "Seleccione un cliente");

                return;
            }

            // Validar que existan productos
            if (lDF.isEmpty()) {

                JOptionPane.showMessageDialog(this,
                        "Debe agregar al menos un producto");

                return;
            }

            // Obtener el cliente
            Cliente cliente = obtenerCliente();

            // Crear la factura
            Factura factura = new Factura();

            factura.setFecha(LocalDate.now());
            factura.setCliente(cliente);
            factura.setListaArticulos(lDF);

            // Guardar la factura
            FacturaControlador fc = new FacturaControlador();

            int idFactura = fc.guardarFactura(factura);

            if (idFactura > 0) {

                JOptionPane.showMessageDialog(this,
                        "Factura guardada correctamente");

                limpiarFactura();

            } else {

                JOptionPane.showMessageDialog(this,
                        "No se pudo guardar la factura");

            }

        } catch (HeadlessException e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());

        }

    }

    private Cliente obtenerCliente() {

        int indice = cmbClientes.getSelectedIndex();

        Cliente cliente;

        String tipo = lC.get(indice)[6];

        if (tipo.equalsIgnoreCase("VIP")) {

            ClienteVIP vip = new ClienteVIP();
            vip.setPorcentajeFidelidad(Double.parseDouble(lC.get(indice)[7]));
            cliente = vip;

        } else {

            cliente = new ClienteRegular();

        }

        cliente.setId(Integer.parseInt(lC.get(indice)[0]));
        cliente.setCedula(lC.get(indice)[2]);
        cliente.setNombre(lC.get(indice)[1]);
        cliente.setEmail(lC.get(indice)[3]);
        cliente.setTelefono(lC.get(indice)[4]);
        cliente.setDireccion(lC.get(indice)[5]);

        return cliente;
    }

    private void limpiarFactura() {

        // Limpiar lista de detalles
        lDF.clear();

        // Deseleccionar cliente y producto
        cmbClientes.setSelectedIndex(-1);
        cmbProductos.setSelectedIndex(-1);

        // Limpiar datos del cliente
        txtCedula.setText("");
        txtDireccion.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");

        // Limpiar detalle
        txtADetalle.setText("");

        // Limpiar campos
        txtPrecio.setText("");
        txtSubTotal.setText("");

        spCantidad.setValue(0);

        chkIVA.setSelected(false);
        chkIVA.setEnabled(false);

        cmbProductos.setEnabled(false);
        spCantidad.setEnabled(false);

        // Actualizar fecha
        cargarFecha();

    }

